-- funkcje

-- funkcja obliczajaca koszt rezerwacji pokoju przy uzyciu ceny zapisanej w momencie rezerwacji STABLE - tylko czyta tabele:
CREATE OR REPLACE FUNCTION koszt_rezerwacji(p_id_rezerwacji integer) RETURNS numeric LANGUAGE sql STABLE AS $$
    SELECT COALESCE(SUM((data_do - data_od) * cena_za_noc), 0) FROM rezerwacja_pokoj WHERE id_rezerwacji = p_id_rezerwacji;
$$;

-- funkcja odpowiadajaca za ksiegowanie wplaty goscia, blokujaca zbyt duze wplaty przekraczajace koszt
CREATE OR REPLACE FUNCTION zaksieguj_wplate(p_id_rezerwacji integer, p_id_pracownika integer, p_kwota numeric, p_rodzaj varchar) RETURNS integer LANGUAGE plpgsql AS $$
DECLARE
    koszt numeric;
    wplacono numeric;
    id integer;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM rezerwacja WHERE id_rezerwacji = p_id_rezerwacji) THEN
        RAISE EXCEPTION 'Rezerwacja % nie istnieje', p_id_rezerwacji;
    END IF;
    koszt := koszt_rezerwacji(p_id_rezerwacji);
    SELECT COALESCE(SUM(kwota), 0) INTO wplacono FROM platnosc WHERE id_rezerwacji = p_id_rezerwacji;
    INSERT INTO platnosc (id_rezerwacji, id_pracownika, kwota, rodzaj) VALUES (p_id_rezerwacji, p_id_pracownika, p_kwota, p_rodzaj) RETURNING id_platnosci INTO id;
    RAISE NOTICE 'Zaksięgowano wpłatę nr %', id;
    RETURN id;
END; $$;

-- funkcja obslugujaca widok wolnych pokojow - dzieki parametrom mozna wyszukiwac wolne pokoje na konkretny dzien a nie tylko na dzisiaj

CREATE OR REPLACE FUNCTION wolne_pokoje(p_od date, p_do date, p_id_typu integer DEFAULT NULL, p_liczba_osob integer DEFAULT NULL)
RETURNS TABLE (numer varchar, typ varchar, liczba_osob smallint, cena_za_noc numeric) LANGUAGE plpgsql STABLE AS $$
BEGIN
    IF p_do <= p_od THEN
        RAISE EXCEPTION 'Data wymeldowania (%) musi być późniejsza niż data zameldowania (%)', p_do, p_od
            USING HINT = 'Podaj daty tak żeby długość pobytu wynosiła co najmniej jedną noc';
    END IF;
    RETURN QUERY SELECT p.numer, t.nazwa, t.liczba_osob, t.cena_za_noc FROM pokoj p JOIN typ_pokoju t ON t.id_typu = p.id_typu
    WHERE (p_id_typu IS NULL OR t.id_typu = p_id_typu) AND (p_liczba_osob IS NULL OR t.liczba_osob >= p_liczba_osob)
    AND NOT EXISTS (SELECT 1 FROM rezerwacja_pokoj rp WHERE rp.id_pokoju = p.id_pokoju AND daterange(rp.data_od, rp.data_do) && daterange(p_od, p_do))
    ORDER BY p.numer;
END; $$;

-- wyzwalacze

-- funkcja + wyzwalacz blokujace wplaty przekraczajace brakujaca naleznosc

CREATE OR REPLACE FUNCTION blokuj_nadplate() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    koszt numeric;
    wplacono numeric;
BEGIN
    koszt := koszt_rezerwacji(NEW.id_rezerwacji);
    SELECT COALESCE(SUM(kwota), 0) INTO wplacono FROM platnosc WHERE 
    id_rezerwacji = NEW.id_rezerwacji AND id_platnosci <> NEW.id_platnosci;
    IF wplacono + NEW.kwota > koszt THEN
        RAISE EXCEPTION 'Wpłata w wysokości % przekracza brakującą dopłatę za rezerwację % (brakuje % zl)', NEW.kwota, NEW.id_rezerwacji, koszt - wplacono
        USING HINT = 'Zaksięguj kwotę nie większą niż pozostała dopłata';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_blokada_nadplaty BEFORE INSERT OR UPDATE ON platnosc 
FOR EACH ROW EXECUTE FUNCTION blokuj_nadplate();

-- widoki

-- widok dla goscia - pokoje wolne w dniu dzisiejszym wykorzystuje funkcje wolne pokoje, ktora z kolei pozwala na wyszukanie wolnych pokojow w dowolnych terminach

CREATE VIEW widok_wolne_pokoje_dzis AS
SELECT * FROM wolne_pokoje(CURRENT_DATE, CURRENT_DATE + 1);

-- widok platnosci dla recepcjonisty: widzi ile zaplacil gosc, ile brakuje jaki jest status, ulatwia ksiegowanie faktycznych platnosci

CREATE VIEW widok_rezerwacje_platnosci AS
SELECT r.id_rezerwacji, r.id_goscia, g.imie, g.nazwisko, r.data_utworzenia,
        COALESCE(k.koszt, 0) AS koszt, COALESCE(w.wplacono, 0) AS wplacono, COALESCE(k.koszt, 0) - COALESCE(w.wplacono, 0) AS do_zaplaty,
        CASE
          WHEN COALESCE(w.wplacono, 0) = 0 THEN 'brak wpłat'
          WHEN COALESCE(w.wplacono, 0) < COALESCE(k.koszt, 0) THEN 'opłacona częściowo'
          ELSE 'opłacona w całości'
        END AS status
FROM rezerwacja r JOIN gosc g ON g.id_goscia = r.id_goscia
LEFT JOIN (SELECT id_rezerwacji, SUM((data_do - data_od) * cena_za_noc) AS koszt FROM rezerwacja_pokoj GROUP BY id_rezerwacji) k ON k.id_rezerwacji = r.id_rezerwacji
LEFT JOIN (SELECT id_rezerwacji, SUM(kwota) AS wplacono FROM platnosc GROUP BY id_rezerwacji) w ON w.id_rezerwacji = r.id_rezerwacji;

-- widok przychodow w danych miesiacach - do raportow administratora
CREATE VIEW widok_przychody AS 
SELECT date_trunc('month', data_wplaty)::date AS miesiac, 
        COUNT(*) AS liczba_wplat, SUM(kwota) AS przychody 
FROM platnosc GROUP BY miesiac ORDER BY miesiac;

-- widok popularnosci (ilosc rezerwacji) pokoju wzgledem typu
CREATE VIEW widok_popularnosci_pokojow AS
SELECT t.nazwa AS typ, COUNT(DISTINCT p.id_pokoju) AS liczba_pokojow,
        COUNT(rp.id_pokoju) AS liczba_rezerwacji, COALESCE(SUM(rp.data_do - rp.data_od), 0) AS zajete_noce
FROM typ_pokoju t LEFT JOIN pokoj p ON t.id_typu = p.id_typu
LEFT JOIN rezerwacja_pokoj rp ON p.id_pokoju = rp.id_pokoju
GROUP BY t.id_typu, typ ORDER BY zajete_noce DESC, liczba_rezerwacji DESC;

-- widok najlepszych gosci do raportow administratora (wydatki powyzej ustalonego progu)
CREATE VIEW widok_najlepszych_gosci AS 
SELECT g.id_goscia, g.imie, g.nazwisko,
        COUNT(DISTINCT r.id_rezerwacji) AS liczba_rezerwacji,
        SUM(pl.kwota) AS suma_wplat
FROM gosc g JOIN rezerwacja r ON g.id_goscia = r.id_goscia
JOIN platnosc pl ON r.id_rezerwacji = pl.id_rezerwacji
GROUP BY g.id_goscia, g.imie, g.nazwisko HAVING SUM(pl.kwota) > 1000
ORDER BY suma_wplat DESC, liczba_rezerwacji DESC;

-- widok najrzadziej rezerwowanych pokojow do raportow administratora
CREATE VIEW widok_rzadkie_pokoje AS
SELECT p.numer, t.nazwa AS typ, COUNT(rp.id_rezerwacji) AS liczba_rezerwacji
FROM typ_pokoju t JOIN pokoj p ON t.id_typu = p.id_typu 
LEFT JOIN rezerwacja_pokoj rp ON p.id_pokoju = rp.id_pokoju
GROUP BY p.id_pokoju, p.numer, t.nazwa HAVING COUNT(rp.id_rezerwacji) < 2
ORDER BY liczba_rezerwacji, p.numer;

-- widok miesiecy z zarobkami powyzej sredniej - raport administratora
CREATE VIEW widok_miesiace_ponad_srednia AS
SELECT date_trunc('month', data_wplaty)::date AS miesiac,
        SUM(kwota) AS przychod
FROM platnosc GROUP BY date_trunc('month', data_wplaty)
HAVING SUM(kwota) > (
        SELECT AVG(suma) FROM (
            SELECT SUM(kwota) AS suma
            FROM platnosc
            GROUP BY date_trunc('month', data_wplaty)) s
) ORDER BY miesiac;