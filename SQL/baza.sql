CREATE EXTENSION IF NOT EXISTS btree_gist;

-- słownik

CREATE TABLE typ_pokoju (
    id_typu integer GENERATED BY DEFAULT AS IDENTITY,
    nazwa varchar(50)  NOT NULL,
    cena_za_noc numeric(8,2) NOT NULL,
    liczba_osob smallint NOT NULL,
    CONSTRAINT typ_pokoju_pk PRIMARY KEY (id_typu),
    CONSTRAINT typ_pokoju_nazwa_uniq UNIQUE (nazwa),
    CONSTRAINT typ_pokoju_cena_chk CHECK (cena_za_noc > 0),
    CONSTRAINT typ_pokoju_osoby_chk CHECK (liczba_osob BETWEEN 1 AND 10)
);

-- role

CREATE TABLE gosc (
    id_goscia integer GENERATED BY DEFAULT AS IDENTITY,
    imie varchar(50)  NOT NULL,
    nazwisko varchar(50)  NOT NULL,
    email varchar(100) NOT NULL,
    numer_telefonu varchar(15)  NOT NULL,
    haslo_hash varchar(255) NOT NULL,
    CONSTRAINT gosc_pk PRIMARY KEY (id_goscia),
    CONSTRAINT gosc_email_uniq UNIQUE (email),
    CONSTRAINT gosc_email_chk CHECK (email LIKE '_%@_%._%'),
    CONSTRAINT gosc_telefon_chk CHECK (numer_telefonu ~ '^\+?[0-9]{9,14}$')
);

CREATE TABLE pracownik (
    id_pracownika integer GENERATED BY DEFAULT AS IDENTITY,
    imie varchar(50) NOT NULL,
    nazwisko varchar(50)  NOT NULL,
    login varchar(50)  NOT NULL,
    haslo_hash varchar(255) NOT NULL,
    rola varchar(20)  NOT NULL,
    CONSTRAINT pracownik_pk PRIMARY KEY (id_pracownika),
    CONSTRAINT pracownik_login_uniq UNIQUE (login),
    CONSTRAINT pracownik_rola_chk CHECK (rola IN ('recepcjonista', 'administrator'))
);

-- pozostałe tabele

CREATE TABLE pokoj (
    id_pokoju integer GENERATED BY DEFAULT AS IDENTITY,
    numer varchar(10) NOT NULL,
    id_typu integer NOT NULL,
    CONSTRAINT pokoj_pk PRIMARY KEY (id_pokoju),
    CONSTRAINT pokoj_numer_uniq UNIQUE (numer),
    CONSTRAINT pokoj_typ_fk FOREIGN KEY (id_typu)
        REFERENCES typ_pokoju (id_typu) ON DELETE RESTRICT
);

CREATE TABLE rezerwacja (
    id_rezerwacji integer GENERATED BY DEFAULT AS IDENTITY,
    id_goscia integer NOT NULL,
    data_utworzenia date NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT rezerwacja_pk PRIMARY KEY (id_rezerwacji),
    CONSTRAINT rezerwacja_gosc_fk FOREIGN KEY (id_goscia)
        REFERENCES gosc (id_goscia) ON DELETE RESTRICT
);

CREATE TABLE rezerwacja_pokoj (
    id_rezerwacji integer NOT NULL,
    id_pokoju integer NOT NULL,
    data_od date NOT NULL,
    data_do date NOT NULL,
    cena_za_noc numeric(8,2) NOT NULL,
    CONSTRAINT rezerwacja_pokoj_pk PRIMARY KEY (id_rezerwacji, id_pokoju),
    CONSTRAINT rezerwacja_pokoj_rez_fk FOREIGN KEY (id_rezerwacji)
        REFERENCES rezerwacja (id_rezerwacji) ON DELETE CASCADE,
    CONSTRAINT rezerwacja_pokoj_pokoj_fk FOREIGN KEY (id_pokoju)
        REFERENCES pokoj (id_pokoju) ON DELETE RESTRICT,
    CONSTRAINT rezerwacja_pokoj_daty_chk CHECK (data_do > data_od),
    CONSTRAINT rezerwacja_pokoj_cena_chk CHECK (cena_za_noc > 0),
    CONSTRAINT rezerwacja_pokoj_kolizja EXCLUDE USING gist (
        id_pokoju WITH =,
        daterange(data_od, data_do) WITH &&
    )
);

CREATE TABLE platnosc (
    id_platnosci  integer GENERATED BY DEFAULT AS IDENTITY,
    id_rezerwacji integer NOT NULL,
    id_pracownika integer NOT NULL,
    kwota numeric(8,2) NOT NULL,
    data_wplaty date NOT NULL DEFAULT CURRENT_DATE,
    rodzaj varchar(20) NOT NULL,
    CONSTRAINT platnosc_pk PRIMARY KEY (id_platnosci),
    CONSTRAINT platnosc_rez_fk FOREIGN KEY (id_rezerwacji)
        REFERENCES rezerwacja (id_rezerwacji) ON DELETE RESTRICT,
    CONSTRAINT platnosc_pracownik_fk FOREIGN KEY (id_pracownika)
        REFERENCES pracownik (id_pracownika) ON DELETE RESTRICT,
    CONSTRAINT platnosc_kwota_chk CHECK (kwota > 0),
    CONSTRAINT platnosc_rodzaj_chk CHECK (rodzaj IN ('zaliczka', 'doplata'))
);

--rozszerzenie: uslugi

CREATE TABLE usluga (
    id_uslugi integer GENERATED BY DEFAULT AS IDENTITY,
    nazwa varchar(50) NOT NULL,
    cena numeric(8,2) NOT NULL,
    CONSTRAINT usluga_pk PRIMARY KEY (id_uslugi),
    CONSTRAINT usluga_nazwa_uniq UNIQUE (nazwa),
    CONSTRAINT usluga_cena_chk CHECK (cena >= 0)
);

CREATE TABLE rezerwacja_usluga (
    id_rez_uslugi integer GENERATED BY DEFAULT AS IDENTITY,
    id_rezerwacji integer NOT NULL,
    id_uslugi integer NOT NULL,
    termin timestamp NOT NULL,
    cena numeric(8,2) NOT NULL,
    CONSTRAINT rezerwacja_usluga_pk PRIMARY KEY (id_rez_uslugi),
    CONSTRAINT rezerwacja_usluga_rez_fk FOREIGN KEY (id_rezerwacji)
        REFERENCES rezerwacja (id_rezerwacji) ON DELETE CASCADE,
    CONSTRAINT rezerwacja_usluga_usluga_fk FOREIGN KEY (id_uslugi)
        REFERENCES usluga (id_uslugi) ON DELETE RESTRICT,
    CONSTRAINT rezerwacja_usluga_cena_chk  CHECK (cena >= 0)
);

-- widoki

-- widok dla goscia - pokoje wolne w dniu dzisiejszym

CREATE VIEW widok_wolne_pokoje AS
SELECT p.numer, t.nazwa AS typ, t.liczba_osob, t.cena_za_noc
FROM pokoj p JOIN typ_pokoju t ON t.id_typu = p.id_typu 
WHERE NOT EXISTS (SELECT 1 FROM rezerwacja_pokoj rp WHERE rp.id_pokoju = p.id_pokoju AND CURRENT_DATE >= rp.data_od AND CURRENT_DATE <  rp.data_do)

-- widok platnosci dla recepcjonisty: widzi ile zaplacil gosc, ile brakuje jaki jest status, ulatwia ksiegowanie faktycznych platnosci

CREATE VIEW widok_rezerwacje_platnosci AS
SELECT r.id_rezerwacji, r.id_goscia, g.imie, g.nazwisko, r.data_utworzenia,
       COALESCE(k.koszt, 0) AS koszt,
       COALESCE(w.wplacono, 0) AS wplacono,
       COALESCE(k.koszt, 0) - COALESCE(w.wplacono, 0) AS do_zaplaty,
       CASE
         WHEN COALESCE(w.wplacono, 0) = 0 THEN 'brak wpłat'
         WHEN COALESCE(w.wplacono, 0) < COALESCE(k.koszt, 0) THEN 'opłacona częściowo'
         ELSE 'opłacona w całości'
       END AS status
FROM rezerwacja r
JOIN gosc g ON g.id_goscia = r.id_goscia
LEFT JOIN (SELECT id_rezerwacji, SUM((data_do - data_od) * cena_za_noc) AS koszt FROM rezerwacja_pokoj GROUP BY id_rezerwacji) k
       ON k.id_rezerwacji = r.id_rezerwacji
LEFT JOIN (SELECT id_rezerwacji, SUM(kwota) AS wplacono FROM platnosc GROUP BY id_rezerwacji) w ON w.id_rezerwacji = r.id_rezerwacji;